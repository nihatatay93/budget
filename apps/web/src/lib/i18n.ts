export function currentLocale(language = globalThis.navigator?.language): AppLocale {
  return language?.toLocaleLowerCase().startsWith("tr") ? "tr" : "en";
}

export function t(
  key: TranslationKey,
  valuesOrLocale?: Record<string, string | number> | AppLocale,
  requestedLocale = currentLocale(),
): string {
  const locale = typeof valuesOrLocale === "string" ? valuesOrLocale : requestedLocale;
  const values = typeof valuesOrLocale === "object" ? valuesOrLocale : undefined;
  const message = locale === "tr"
    ? turkishMessages[key] ?? (messages.tr as Record<string, string>)[key] ?? key
    : englishMessages[key] ?? (messages.en as Record<string, string>)[key] ?? key;
  return values
    ? message.replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? `{${name}}`))
    : message;
}

export function roleLabel(role: string): string {
  return t(role);
}

type LocalizedCategory = {
  kind?: "expense" | "income";
  name: string;
  predefined_key?: string;
  system_key?: string;
};

export function categoryName(category: LocalizedCategory, locale = currentLocale()): string {
  if (category.predefined_key) {
    const kinds = category.kind ? [category.kind] : ["expense", "income"];
    for (const kind of kinds) {
      const key = `category.${kind}.${category.predefined_key}` as TranslationKey;
      if (key in messages.en) return t(key, locale);
    }
  }
  if (category.system_key) {
    const key = `category.system.${category.system_key}` as TranslationKey;
    if (key in messages.en) return t(key, locale);
  }
  return category.name;
}
